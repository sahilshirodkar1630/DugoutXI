package com.sahilprojects.bettingApp.league;

import com.sahilprojects.bettingApp.common.BaseEntity;
import com.sahilprojects.bettingApp.tournament.Tournament;
import com.sahilprojects.bettingApp.user.User;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.Instant;

@Entity
@Table(name = "leagues")
@Getter
@Setter
public class League extends BaseEntity {

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "organizer_id", nullable = false)
    private User organizer;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "tournament_id", nullable = false)
    private Tournament tournament;

    @Column(nullable = false)
    private String name;

    @Column(name = "amount_per_contest", nullable = false, precision = 10, scale = 2)
    private BigDecimal amountPerContest;

    @Column(name = "total_contests", nullable = false)
    private Integer totalContests;

    /** Generated by the database (amount_per_contest * total_contests). Read only. Refresh after saving to see it. */
    @Column(name = "joining_amount", insertable = false, updatable = false, precision = 12, scale = 2)
    private BigDecimal joiningAmount;

    @Column(name = "registration_start", nullable = false)
    private Instant registrationStart;

    @Column(name = "registration_deadline", nullable = false)
    private Instant registrationDeadline;

    @Column(name = "payment_deadline", nullable = false)
    private Instant paymentDeadline;

    @Column(name = "payment_instructions")
    private String paymentInstructions;

    @Column(name = "invite_code", nullable = false, unique = true)
    private String inviteCode;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private LeagueStatus status = LeagueStatus.UPCOMING;

    @Column(name = "started_at")
    private Instant startedAt;

    @Column(name = "ended_at")
    private Instant endedAt;

    @Column(name = "completed_at")
    private Instant completedAt;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "force_closed_by")
    private User forceClosedBy;

    @Column(name = "force_close_reason")
    private String forceCloseReason;
}
