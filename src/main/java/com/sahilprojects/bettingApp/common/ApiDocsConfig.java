package com.sahilprojects.bettingApp.common;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.tags.Tag;
import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import java.util.List;

/**
 * The OpenAPI description of the API, generated by springdoc from the controllers and request records, so it cannot
 * drift from the code. Served at /v3/api-docs and shown by the Scalar page at /docs (ApiDocsController).
 *
 * Off unless springdoc.api-docs.enabled is true (API_DOCS_ENABLED), so a public deployment does not hand out a map
 * of every admin endpoint by default.
 */
@Configuration
@ConditionalOnProperty(name = "springdoc.api-docs.enabled", havingValue = "true")
public class ApiDocsConfig {

    static final String BEARER = "bearerAuth";

    /** Groups in the order a season happens. Controllers name their group with @Tag. */
    static final List<Tag> TAGS = List.of(
            tag("Auth", "Register, sign in, and ask the admins for a password reset. No token needed."),
            tag("Me", "Your profile, password, record (all time or by period) and your own Excel history."),
            tag("Tournaments", "The tournaments and teams leagues and contests are built on."),
            tag("Leagues", "Create and run a season-long league. Everyone pays the whole season up front."),
            tag("League members", "Asking to join a league, and the organizer accepting, confirming payment or removing."),
            tag("Contests", "Matches: league contests (send leagueId) and one-off contests with their own entry."),
            tag("Contest players", "Asking for a place in a one-off contest, and the organizer letting people in."),
            tag("Picks", "Picking the winner. Other people's picks stay hidden until the match starts."),
            tag("Results", "Declaring a result takes two steps: preview returns a token, confirm sends it back. "
                    + "A pick that changed in between makes the token stale and the confirm is refused."),
            tag("Payouts", "One-off contests settle at once: who is owed winnings or a refund, and marking them paid."),
            tag("Settlement", "Ending a league: every member's final balance, handed back by the organizer."),
            tag("Board", "League tables and your own summary."),
            tag("Exports", "Excel copies of a league season or of your own history."),
            tag("Notifications", "In-app alerts. The app polls the unread count; there is no email or push."),
            tag("Admin", "Accounts, tournaments and teams. Admin only; changes for someone else need a written reason."),
            tag("Dev tools", "Shortcuts for trying the app out. Only present when app.dev-tools.enabled is true."));

    @Bean
    OpenAPI dugoutOpenApi() {
        return new OpenAPI()
                .info(new Info()
                        .title("Dugout XI API")
                        .version("1")
                        .description("""
                                A cricket prediction league for friends: pick who wins each match, and the app keeps \
                                the score and the money straight. **No money moves through the app**; it records who \
                                has paid and who is owed what.

                                **Signing in.** Call `POST /api/auth/login` (or `register`), then send the token as \
                                `Authorization: Bearer <token>`. In this page, use the Authentication box with the token.

                                **Money** amounts are decimals with two places, worked out with BigDecimal on the \
                                server; do not add them up as floating point.

                                **Errors** come back as `application/problem+json` with a `code` (such as \
                                `BAD_REQUEST`, `FORBIDDEN`, `NOT_FOUND`, `CONFLICT`) and a `detail` written to be shown \
                                to the user. Validation failures add an `errors` map of field to message.

                                **Who may do what** is checked per league or contest: whoever created it is its \
                                organizer. An admin may act in an organizer's place, but only with a written reason, \
                                which goes into the audit log."""))
                .components(new Components().addSecuritySchemes(BEARER, new SecurityScheme()
                        .type(SecurityScheme.Type.HTTP)
                        .scheme("bearer")
                        .bearerFormat("JWT")
                        .description("The token from sign-in or registration. It lasts 24 hours.")))
                .addSecurityItem(new SecurityRequirement().addList(BEARER))
                .tags(TAGS);
    }

    /** Sign-in and registration need no token, so the padlock is taken off them. */
    @Bean
    OpenApiCustomizer publicAuthEndpoints() {
        return openApi -> openApi.getPaths().forEach((path, item) -> {
            if (path.startsWith("/api/auth/")) {
                item.readOperations().forEach(op -> op.setSecurity(List.of()));
            }
        });
    }

    private static Tag tag(String name, String description) {
        return new Tag().name(name).description(description);
    }
}
